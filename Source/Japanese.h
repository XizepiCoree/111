inline juce::String tr (const char* en)
{
    if (secretFlag())
        for (const auto& e : jpTable)
            if (std::strcmp (e.en, en) == 0)
                return juce::String::fromUTF8 (e.ja);

    return juce::String::fromUTF8 (en);
}

